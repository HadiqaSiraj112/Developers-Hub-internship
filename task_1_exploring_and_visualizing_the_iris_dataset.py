# STEP 1: Import libraries
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# STEP 2: Load the Iris dataset
df = sns.load_dataset('iris')

# STEP 3: Explore dataset structure
print("=" * 50)
print("DATASET SHAPE (rows, columns):", df.shape)

print("\nCOLUMN NAMES:")
print(df.columns.tolist())

print("\nFIRST 5 ROWS:")
print(df.head())

print("\nDATASET INFO:")
print(df.info())

print("\nBASIC STATISTICS:")
print(df.describe())

print("\nSPECIES COUNT:")
print(df['species'].value_counts())

# STEP 4: Visualizations
# Plot 1: Scatter Plot (Sepal Length vs Petal Length)
plt.figure(figsize=(8, 5))
sns.scatterplot(data=df, x='sepal_length', y='petal_length',
                hue='species', palette='Set1', s=80)
plt.title('Scatter Plot: Sepal Length vs Petal Length')
plt.xlabel('Sepal Length (cm)')
plt.ylabel('Petal Length (cm)')
plt.legend(title='Species')
plt.tight_layout()
plt.savefig('task1_scatter.png', dpi=150)
plt.show()
print("Scatter plot saved as task1_scatter.png")

#Plot 2: Histogram (Distribution of Sepal Length)
plt.figure(figsize=(8, 5))
for species in df['species'].unique():
    subset = df[df['species'] == species]
    plt.hist(subset['sepal_length'], alpha=0.6, bins=12, label=species)
plt.title('Histogram: Sepal Length Distribution by Species')
plt.xlabel('Sepal Length (cm)')
plt.ylabel('Frequency')
plt.legend(title='Species')
plt.tight_layout()
plt.savefig('task1_histogram.png', dpi=150)
plt.show()
print("Histogram saved as task1_histogram.png")

# Plot 3: Box Plot (All numeric features by species)
plt.figure(figsize=(12, 6))
df_melted = df.melt(id_vars='species', var_name='Feature', value_name='Value')
sns.boxplot(data=df_melted, x='Feature', y='Value', hue='species', palette='Set2')
plt.title('Box Plot: Feature Distribution by Species')
plt.xlabel('Feature')
plt.ylabel('Value (cm)')
plt.legend(title='Species')
plt.tight_layout()
plt.savefig('task1_boxplot.png', dpi=150)
plt.show()
print("Box plot saved as task1_boxplot.png")